/**
 * The coordinates of a frame on a spritesheet
 */
export default interface IFrameCoordinates {
    
    /**
     * The x position
     */
    x:number;
    
    /**
     * The y position
     */
    y:number;
    
    /**
     * The width dimension
     */
    width:number;
    
    /**
     * The height dimension
     */
    height:number;
    
};